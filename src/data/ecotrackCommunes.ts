function normalizeArabicKey(raw: string): string {
  return String(raw || '')
    .replace(/\u0640/g, '') // strip tatweel
    .replace(/[\u064B-\u065F\u0670]/g, '') // strip harakat
    .replace(/[أإآ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/[()\-_,./]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function stripLatinNorm(input: string): string {
  return String(input || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function hasArabicChars(input?: string): boolean {
  return /[\u0600-\u06FF]/.test(String(input || ''));
}

