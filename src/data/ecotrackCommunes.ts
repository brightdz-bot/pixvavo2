const AR_OVERRIDE_MAP = new Map<string, string>();
for (const [wCode, ar, fr] of RAW_AR_OVERRIDES) {
  AR_OVERRIDE_MAP.set(`${wCode}:${normalizeArabicKey(ar)}`, fr);
}

export interface OfficialCommuneResolution {
  wilayaCode: number;
  commune: string;
  matched: boolean;
  ranked: string[];
}

function toConsonantSkeleton(latin: string): string {
  return stripLatinNorm(latin)
    .replace(/x/g, 'ks')
    .replace(/qu/g, 'k')
    .replace(/ph/g, 'f')
    .replace(/ch/g, 'sh')
    .replace(/dj/g, 'j')
    .replace(/gh/g, 'G')
    .replace(/kh/g, 'X')
    .replace(/th/g, 't')
    .replace(/dh/g, 'd')
    .replace(/c(?=[eiy])/g, 's')
    .replace(/c/g, 'k')
    .replace(/q/g, 'k')
    .replace(/g/g, 'k')
    .replace(/z/g, 's')
    .replace(/v/g, 'f')
    .replace(/w/g, 'o')
    .replace(/\b(el|al)\b/g, '')
    .replace(/[aeiouy\s]/g, '')
    .replace(/(.)\1+/g, '$1');
}

function editSimilarity(a: string, b: string): number {
  if (!a || !b) return 0;
  if (a === b) return 1;
  const m = a.length;
  const n = b.length;
  const dp: number[] = Array.from({ length: n + 1 }, (_, j) => j);
  for (let i = 1; i <= m; i++) {
    let prev = dp[0];
    dp[0] = i;
    for (let j = 1; j <= n; j++) {
      const temp = dp[j];
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      dp[j] = Math.min(dp[j] + 1, dp[j - 1] + 1, prev + cost);
      prev = temp;
    }
  }
  const maxLen = Math.max(m, n);
  return maxLen > 0 ? 1 - dp[n] / maxLen : 0;
}

export function resolveOfficialEcotrackCommune(
  wilayaCodeInput: number | string,
  rawCommune?: string | null
): OfficialCommuneResolution {
  const numCode = parseInt(String(wilayaCodeInput || ''), 10);
  const wilayaCode = numCode >= 1 && numCode <= 58 ? numCode : 16;
  const officialList = ECOTRACK_COMMUNES_BY_WILAYA[wilayaCode] || ECOTRACK_COMMUNES_BY_WILAYA[16];
  const hub = ECOTRACK_WILAYA_HUB[wilayaCode] || officialList[0] || 'Alger Centre';

  const trimmed = String(rawCommune || '').trim();
  if (!trimmed) {
    return {
      wilayaCode,
      commune: hub,
      matched: false,
      ranked: [hub, ...officialList.filter(c => c !== hub)]
    };
  }

  // 1. Exact French match (case-insensitive / diacritic-insensitive)
  const normLatinInput = stripLatinNorm(trimmed);
  if (normLatinInput) {
    const exactFr = officialList.find(c => stripLatinNorm(c) === normLatinInput);
    if (exactFr) {
      return {
        wilayaCode,
        commune: exactFr,
        matched: true,
        ranked: [exactFr, hub, ...officialList.filter(c => c !== exactFr && c !== hub)]
      };
    }
  }

  // 2. Explicit Arabic override match
  if (hasArabicChars(trimmed)) {
    const arKey = `${wilayaCode}:${normalizeArabicKey(trimmed)}`;
    const override = AR_OVERRIDE_MAP.get(arKey);
    if (override && officialList.includes(override)) {
      return {
        wilayaCode,
        commune: override,
        matched: true,
        ranked: [override, hub, ...officialList.filter(c => c !== override && c !== hub)]
      };
    }
  }

  // 3. Multi-variant Algerian Arabic transliteration + consonant-skeleton + edit-distance ranking
  const variants = hasArabicChars(trimmed)
    ? Array.from(
        new Set([
          transliterateArabicDz(trimmed, 'k', 'dj'),
          transliterateArabicDz(trimmed, 'g', 'dj'),
          transliterateArabicDz(trimmed, 'k', 'j'),
          transliterateArabicDz(trimmed, 'g', 'j'),
          transliterateArabicDz(trimmed.replace(/^ال/, ''), 'k', 'dj'),
          transliterateArabicDz(trimmed.replace(/^ال/, ''), 'g', 'dj')
        ])
      ).filter(Boolean)
    : [normLatinInput].filter(Boolean);

  const variantSkeletons = Array.from(
    new Set(variants.map(v => toConsonantSkeleton(v)).filter(Boolean))
  );

  const hubNorm = stripLatinNorm(hub);
  const scored = officialList
    .map(cand => {
      const candNorm = stripLatinNorm(cand);
      const candSkel = toConsonantSkeleton(cand);
      let bestScore = 0;

      for (const v of variants) {
        let s = 0.55 * bigramSimilarity(v, candNorm) + 0.45 * editSimilarity(v, candNorm);
        if (candNorm === v) s += 2.0;
        if (s > bestScore) bestScore = s;
      }

      for (const skel of variantSkeletons) {
        if (!skel || !candSkel) continue;
        let skelScore =
          0.5 * editSimilarity(skel, candSkel) + 0.5 * bigramSimilarity(skel, candSkel);
        if (skel === candSkel) skelScore += 1.4;
        else if (skel.length >= 4 && candSkel === skel) skelScore += 1.0;
        if (skelScore > bestScore) bestScore = skelScore;
      }

      if (candNorm === hubNorm) bestScore += 0.01;
      return { name: cand, score: bestScore };
    })
    .sort((a, b) => b.score - a.score);

  const top = scored[0];
  const ranked = scored.map(s => s.name);
  if (top && top.score >= 0.45) {
    return {
      wilayaCode,
      commune: top.name,
      matched: true,
      ranked
    };
  }

  return {
    wilayaCode,
    commune: hub,
    matched: false,
    ranked: [hub, ...ranked.filter(c => c !== hub)]
  };
}
